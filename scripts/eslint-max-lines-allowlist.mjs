#!/usr/bin/env node
/**
 * eslint-max-lines-allowlist.mjs — generates/verifies the max-lines ratchet allowlist.
 *
 * Purpose: ASI Policy 3 caps every file at <=300 lines. The shared `max-lines` rule
 *          added to packages/config/eslint/base.js is `error` repo-wide, but admin's
 *          src/ carries pre-existing oversized files (companion-GUI legacy debt).
 *          This script walks admin's own source, counts each file's effective line
 *          count (blank + comment-only lines excluded, mirroring the rule's
 *          skipBlankLines + skipComments options), and records files over the cap
 *          in eslint-max-lines-allowlist.json so packages/config/eslint/base.js can
 *          downgrade just those files to `warn` — new files, and anything not
 *          already listed, stay `error`.
 * Inputs:  admin repo tree (this script's own location determines the repo root).
 * Outputs: eslint-max-lines-allowlist.json (write mode, default) OR a non-zero exit
 *          with a diff report (verify mode, `--check`) when a file exceeds the cap
 *          without already being in the committed allowlist.
 * Constraints:
 *   - The list must only shrink over time: `--check` never fails because an entry
 *     was REMOVED (a file got split under the cap) — only when a file is over the
 *     cap and MISSING from the committed list (a new, unrecorded violation).
 *   - Line counting is a fast heuristic, not a full AST walk; ESLint's own
 *     `max-lines` rule remains authoritative at lint time. Re-run --write after
 *     splitting a file to drop it from the list.
 * Usage:
 *   node scripts/eslint-max-lines-allowlist.mjs --write   # regenerate the file
 *   node scripts/eslint-max-lines-allowlist.mjs --check   # CI: fail on new debt
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = path.resolve(__dirname, '..')
const ALLOWLIST_PATH = path.join(REPO_ROOT, 'eslint-max-lines-allowlist.json')
const MAX_LINES = 300

const EXCLUDED_DIR_NAMES = new Set([
  'node_modules', 'dist', 'build', '.next', '.turbo', '.cache',
  'coverage', 'out', '.git', 'public', 'e2e',
])
const SOURCE_ROOTS = ['src']
const SOURCE_EXTENSIONS = new Set(['.ts', '.tsx', '.js', '.jsx'])
const EXCLUDED_FILE_PATTERNS = [/\.config\.(m|c)?[jt]s$/, /\.d\.ts$/]

function* walk(dir) {
  let entries
  try {
    entries = readdirSync(dir, { withFileTypes: true })
  } catch {
    return
  }
  for (const entry of entries) {
    if (entry.isDirectory()) {
      if (EXCLUDED_DIR_NAMES.has(entry.name)) continue
      yield* walk(path.join(dir, entry.name))
    } else if (entry.isFile()) {
      yield path.join(dir, entry.name)
    }
  }
}

function countEffectiveLines(text) {
  const lines = text.split(/\r?\n/)
  let count = 0
  let inBlockComment = false
  for (const raw of lines) {
    const line = raw.trim()
    if (inBlockComment) {
      if (line.includes('*/')) inBlockComment = false
      continue
    }
    if (line === '') continue
    if (line.startsWith('//')) continue
    if (line.startsWith('/*')) {
      if (!line.includes('*/')) inBlockComment = true
      continue
    }
    count++
  }
  return count
}

function computeOffenders() {
  const offenders = []
  for (const root of SOURCE_ROOTS) {
    const rootDir = path.join(REPO_ROOT, root)
    for (const file of walk(rootDir)) {
      const ext = path.extname(file)
      if (!SOURCE_EXTENSIONS.has(ext)) continue
      const base = path.basename(file)
      if (EXCLUDED_FILE_PATTERNS.some((re) => re.test(base))) continue
      const text = readFileSync(file, 'utf8')
      if (countEffectiveLines(text) > MAX_LINES) {
        offenders.push(path.relative(REPO_ROOT, file).split(path.sep).join('/'))
      }
    }
  }
  return offenders.sort()
}

function loadCommitted() {
  if (!existsSync(ALLOWLIST_PATH)) return []
  const raw = JSON.parse(readFileSync(ALLOWLIST_PATH, 'utf8'))
  return raw.files ?? []
}

const mode = process.argv.includes('--check') ? 'check' : 'write'
const current = computeOffenders()

if (mode === 'write') {
  const payload = {
    _comment:
      'GENERATED BY scripts/eslint-max-lines-allowlist.mjs -- do not hand edit. ' +
      'Files listed here exceed the 300-line ASI Policy 3 cap and are ratcheted to ' +
      '`warn` in packages/config/eslint/base.js; every other file is `error`. ' +
      'Re-run `node scripts/eslint-max-lines-allowlist.mjs --write` after splitting ' +
      'a file to drop it from this list -- the list must only shrink.',
    generated: new Date().toISOString().slice(0, 10),
    max_lines: MAX_LINES,
    files: current,
  }
  writeFileSync(ALLOWLIST_PATH, JSON.stringify(payload, null, 2) + '\n')
  console.log(`Wrote ${ALLOWLIST_PATH} — ${current.length} offending files.`)
  process.exit(0)
}

const committed = new Set(loadCommitted())
const newViolations = current.filter((f) => !committed.has(f))

if (newViolations.length) {
  console.error('New files exceed the 300-line cap and are not in eslint-max-lines-allowlist.json:')
  for (const f of newViolations) console.error(`  - ${f}`)
  console.error('\nSplit the file(s), or if truly unavoidable run --write to record them (list must only shrink over time).')
  process.exit(1)
}

console.log('OK — no new files exceed the 300-line cap beyond the recorded allowlist.')
process.exit(0)
